"""이 거래소가 다루는 주제인가 — 단일 판정 (ADR-0039).

## 왜 별도 호출인가

`"삼성전자 주식 어때?"` 가 시세 예측 분기를 그대로 타고 **"삼성전자 주식의
최근 거래가는 약 26,090원"** 이라고 답했다. 숫자는 `게임 머니 1000만 골드` 의
진짜 예측값이었고 주어만 거짓이었다.

처음에는 `understand_query` 의 JSON 스키마에 `in_domain` 필드를 하나 더하는
쪽으로 만들었다 — **LLM 호출이 늘지 않는다**는 게 그 안의 장점이었다. 두 번
측정했고 두 번 다 기각됐다.

| | 1회차 | 2회차(문구 수정) | 기준 |
|---|---|---|---|
| 미검출 | 0/38 | 0/38 | <= 10% |
| 오거부(전체 509건) | 29.9% | **13.4%** | <= 1% |
| 재작성 토큰집합 일치 (대조군 대비) | **-0.234** | **-0.248** | 0 이상 |

두 가지가 드러났다.

1. **모델은 판정 자체를 아주 잘한다** — 서로 다른 문구로 두 번, 38건을 하나도
   놓치지 않았다.
2. **문제는 "같은 호출에 얹은 것"이다.** 재작성 손실이 문구를 고쳐도 그대로였다.
   즉 문구가 아니라 **스키마에 필드가 하나 늘어난 것 자체**의 대가다. 재작성
   텍스트는 BM25 와 kNN 양쪽에 들어가므로 검색 품질에 직결된다.

그래서 판정을 떼어냈다. 추출 프롬프트를 건드리지 않으므로 **회귀가 구조적으로
0**이고, 판정 전용 프롬프트라 문구를 정밀하게 쓸 수 있다. 대가는 호출 1회
증가인데, `asyncio.gather` 로 질의이해와 **동시에** 던지므로 지연은 거의 늘지
않는다(둘 다 I/O 대기다).

## 두 번의 실패가 프롬프트에 남긴 것

오거부된 것들을 읽고 넣은 문장들이다. 지어낸 규칙이 아니라 **걸린 표본에서
나온 규칙**이다.

- 1회차에서 거절된 것의 35%가 **시세 질문**이었다(`"골드는 언제쯤 올라?"`).
  `"거래에 관한 질의"` 라고 썼더니 모델이 가격 전망을 "거래"로 읽지 않았다.
- 2회차의 잔여 오거부는 성격이 달랐다 — `"이거 괜찮아?"`, `"저거 어때?"`,
  `"그냥 봐줘"` 처럼 **대상이 흐릿한** 질의다. 주제가 밖인 게 아니다. 그건
  파이프라인이 이미 `_has_target()` 으로 처리해 에이전트로 올리는 경우라,
  게이트가 가로채면 안 된다.
- 전용 프롬프트 1회차(전체 4.13%)의 잔여는 또 달랐다 — `"폭창"`, `"55방각반"`,
  `"쇠뇌 관통"`, `"8강 롱검"` 처럼 **모델이 모르는 게임 은어**와,
  `"HP 최대치 회복하는 물약 있어?"` 처럼 **성능을 묻는 것을 게임 지식 질문으로
  읽은** 경우다.

### 취급 품목 목록과 "플레이 방법은 NO" 는 **역효과였다**

위를 고치면서 네 가지를 한꺼번에 넣었다 — 취급 품목 목록, "성능 질문도 YES",
"이름·은어만 있어도 YES", "플레이 방법은 NO". 오거부가 **4.13% → 5.30%** 로
올라갔고 경계 세트도 0/16 → 2/16 이 됐다.

거절된 것을 읽으니 원인이 둘이었다.

| 넣은 것 | 새로 잘린 것 |
|---|---|
| 취급 품목 목록 | `"고대 유물 조각 구합니다"`, `"수정으로 만든 마법 아이템 찾기"` — **목록에 없는 이름** |
| "플레이 방법은 NO" | `"스킬 쿨타임 줄이는 장신구"`, `"장비 강화 할 때 쓰는 아이템"` — `스킬`·`강화` 라는 **낱말**에 걸렸다 |

> **목록을 주면 모델은 목록 밖을 자른다.** 열거는 포함을 넓히려고 넣었는데
> 배제의 근거로 쓰였다. 금지 규칙도 마찬가지로 의미가 아니라 **낱말**에 걸린다
> — 이 저장소가 정규식에서 두 번 겪은 것과 같은 실패가 프롬프트에서 반복됐다.

그래서 둘을 걷어내고 완화 두 개만 남겼다. **앞선 네 번의 실행에서 미검출은
언제나 0/38 이었다** — 가장 관대한 문구에서도 하나도 안 놓쳤으므로, 관대한
쪽으로 미는 것이 안전하다는 근거가 있었다.

## 채택된 수치와 그 한계

| | 미검출 | 오거부(509) | 오거부(라벨 141) |
|---|---|---|---|
| 기준 | <= 10% | <= 1% | 0건 |
| 결과 | **2.6%** (1/38) | **0.59%** (3/509) | **0건** |

관대해진 대가로 `"초보자 직업 뭐가 나아"` 하나가 통과한다. 실패 방향이 온건하다 —
검색이 돌아 아이템 몇 건이 나올 뿐, 없는 사실을 지어내지 않는다.

> **이 오거부 수치는 in-sample 이고 낙관적이다.** 규칙을 걸린 표본을 읽고 썼기
> 때문이다. 프롬프트의 예시만은 평가셋 563문장에 없는 것으로 지어냈지만
> (`"9강 대검"`, `"70방투구"`, `"빙결 스태프"`), 규칙 자체의 출처는 이 세트다.
> 반면 **미검출 쪽은 다섯 번 내내 문구를 그쪽에 맞춘 적이 없어** 상대적으로
> 정직하다.

남은 오거부 3건은 전부 질의라기보다 혼잣말이다 — `"그냥 지나치기 아깝네"`,
`"사람들이 어떻게 생각하나?"`, `"이 요청은 어떻게 생각해?"`. 경계 세트에서는
`"돈 되는 거 뭐 있어"`, `"3만원 이하로 살 만한 거"` 둘이 막힌다(16건 중 2건).
**대상이 아예 없는 질의는 이 게이트로 구제되지 않는다** — 그건 프롬프트가 아니라
"막연함"과 "주제 이탈"이 한 불리언에 눌려 있다는 구조의 한계다.

> **프롬프트의 예시는 평가셋에 없는 것으로 지어냈다** (`"9강 대검"`,
> `"70방투구"`, `"빙결 스태프"`). 걸린 표본을 그대로 넣으면 그 질의는 다음
> 측정에서 자동으로 맞고, 오거부율이 실력이 아니라 암기가 된다. 그래도 규칙
> 자체는 걸린 표본을 읽고 썼으므로 **최종 오거부 수치는 in-sample 이고 낙관적**
> 이다 — 그 한계는 ADR-0039 에 적어뒀다.

## 실패는 통과다

판정이 안 되면(호출 실패, 예상 밖 출력) **True 를 돌려준다.** 게이트가 죽었을
때 서비스가 "아무것도 답하지 않는" 상태가 되는 쪽이 훨씬 나쁘다.
`understand_query` 가 파싱 실패에 필터를 비우고 원본 질의로 검색하는 것과 같은
방향이고, AI 요청 한도가 Redis 장애에 fail-open 하는 것과도 같다.

대가는 **게이트가 조용히 열린다**는 것이다. 그래서 열린 걸 알 수 있어야 하고,
그건 로그와 `ai_requests_total{outcome="out_of_domain"}` 이 맡는다.
"""

from __future__ import annotations

import logging

from app.services.llm.base import LLMClient

logger = logging.getLogger(__name__)

# 한 단어만 받는다. JSON 을 요구하면 파싱 실패 경로가 생기는데, 이 판정은
# 값이 둘뿐이라 그 복잡도를 살 이유가 없다.
_PROMPT = """다음은 사용자가 게임 아이템 거래소에 입력한 문장입니다.
이 거래소는 게임 아이템·게임 계정·게임 재화(골드)를 사고파는 곳입니다.

이 거래소에서 다룰 수 있는 이야기면 YES, 아니면 NO 만 출력하세요.
다른 말은 쓰지 마세요.

- 게임 안의 물건(장비·아이템·계정·게임 재화)에 대한 이야기는 **전부 YES**입니다.
  찾기, 값 묻기, 오를지 묻기, 살지 말지 고민, 성능 비교, 거래 점검이 다
  포함됩니다.
- **이름·은어·줄임말·오타만 있어도 YES**입니다. 무슨 뜻인지 몰라도 게임 안의
  물건 이름처럼 보이면 YES입니다(예: "9강 대검", "70방투구", "빙결 스태프").
- 무엇을 가리키는지 막연해도(예: "이거 괜찮아?", "그냥 봐줘") YES입니다.
- 짧거나 초성만 있어도(예: "ㄱㅊ?") 판단이 안 서면 YES입니다.
- 게임 아이템 거래와 **아무 상관 없는 주제**일 때만 NO입니다.

문장: {query}"""


async def judge_in_domain(llm_client: LLMClient, query: str) -> bool:
    """이 거래소가 다루는 주제인가. 판정이 안 되면 True(통과)."""
    try:
        raw = await llm_client.complete(_PROMPT.format(query=query))
    except Exception:
        logger.warning("도메인 판정 실패 — 통과로 진행한다", exc_info=True)
        return True
    return _parse(raw)


def _parse(raw: str) -> bool:
    """`NO` 로 시작할 때만 거절.

    **`"NO" in text` 로 쓰면 안 된다** — 모델이 설명을 붙이면
    `"YES, 이 문장은 ... NO 라고 볼 수 없습니다"` 같은 출력에서 뒤집힌다.
    앞을 보고, 그 밖의 모든 출력은 통과다(실패는 통과라는 정책 그대로).
    """
    text = raw.strip().upper().lstrip("*_`\"' ")
    return not (text.startswith("NO") or text.startswith("아니"))
