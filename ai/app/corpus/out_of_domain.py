"""도메인 밖 질의 평가셋 — 전부 수작업.

## 왜 필요한가

배포된 화면에서 `"삼성전자 주식 어때?"` 가 **시세 예측 분기를 그대로 탔다.**
분류기가 `price_forecast` 를 0.9179 로 확신했고, 라우터의 출력 공간에
"내 도메인이 아니다" 가 없어서 5개 의도 중 하나로 강제 배정된 것이다. kNN 은
언제나 k 건을 돌려주므로 검색은 `게임 머니 1000만 골드` 를 찾아냈고, 설명 LLM
은 **질의의 주어를 채택해** "삼성전자 주식의 최근 거래가는 약 26,090원" 이라고
답했다. 숫자는 진짜였고 주어만 거짓이었다.

## 두 목록이 있는 이유

거절 게이트의 실패는 **양방향**이고 대가가 다르다.

| 방향 | 목록 | 대가 |
|---|---|---|
| 도메인 밖을 통과시킴 | `OUT_OF_DOMAIN` | 위와 같은 확신에 찬 거짓말 |
| 도메인 안을 거절함 | `LOOKS_OUT_BUT_IN` | 멀쩡한 검색이 "범위 밖" 이라고 거절됨 |

**뒤쪽만 있는 검사는 항상 통과하고, 앞쪽만 있는 검사는 "전부 거절" 로도 만점을
받는다.** 둘을 같이 재야 지표가 의미를 갖는다.

`LOOKS_OUT_BUT_IN` 은 일부러 **표면이 도메인 밖처럼 보이는 도메인 안 질의**로만
채웠다. `"롱소드 찾아줘"` 같은 명백한 질의를 넣으면 오거부율이 0 으로 나오기
쉬워지는데, 그건 게이트가 안전하다는 증거가 아니라 **표본이 쉬웠다**는 뜻이다.

## LLM 으로 만들지 않은 이유

`intent_utterances.py` 와 같다 — 평가셋을 LLM 으로 만들면 판정자와 출제자가
같은 모델이 되어, 그 모델이 "도메인 밖" 이라고 여기는 것만 도메인 밖이 된다.
게이트가 놓치는 종류는 정의상 그 모델이 생각하지 못한 것들이다.

## 게임 이야기지만 이 거래소 밖인 것 — 가장 어려운 부류

`"이 보스 어떻게 잡아?"` 는 게임 이야기이고 어휘도 겹치지만 **아이템 거래가
아니다.** 이 부류를 빼면 게이트가 "게임 단어가 있으면 통과" 로 동작해도 만점이
나온다. 실제로 이 저장소는 검사가 스스로 틀린 사례를 18건 기록하고 있다.
"""

from __future__ import annotations

# --- 도메인 밖 -------------------------------------------------------------
#
# 이 거래소가 다루지 않는 주제. 게이트는 이걸 전부 거절해야 한다.
OUT_OF_DOMAIN: list[tuple[str, str]] = [
    # 현실 금융 — 관측된 결함이 나온 부류다. "시세" 어휘가 그대로 겹친다.
    ("삼성전자 주식 어때?", "현실금융"),
    ("비트코인 지금 사도 될까", "현실금융"),
    ("달러 환율 오를까요", "현실금융"),
    ("금값 시세 알려줘", "현실금융"),
    ("코스피 전망 어때", "현실금융"),
    ("적금 이자율 제일 높은 데가 어디야", "현실금융"),
    # 현실 상품 — "최저가", "얼마" 가 겹친다.
    ("아이폰 16 최저가 알려줘", "현실상품"),
    ("나이키 운동화 270 있어?", "현실상품"),
    ("중고차 시세 좀 봐줘", "현실상품"),
    ("에어컨 설치비 얼마나 들어", "현실상품"),
    ("서울 아파트 전세 얼마야", "현실상품"),
    # 게임 이야기지만 거래가 아님 — 어휘가 가장 많이 겹치는 부류.
    ("이 보스 어떻게 잡아?", "게임비거래"),
    ("전사 스킬트리 추천해줘", "게임비거래"),
    ("레벨 200 찍는 데 얼마나 걸려", "게임비거래"),
    ("서버 점검 언제 끝나", "게임비거래"),
    ("이번 패치 노트 요약해줘", "게임비거래"),
    ("길드원 구하는 방법 알려줘", "게임비거래"),
    ("초보자 직업 뭐가 나아", "게임비거래"),
    # 날씨 · 생활
    ("오늘 날씨 어때", "생활"),
    ("내일 비 와?", "생활"),
    ("김치찌개 레시피 알려줘", "생활"),
    ("강남역 맛집 추천", "생활"),
    ("지하철 막차 몇 시야", "생활"),
    # 일반 지식 · 학습
    ("대한민국 수도가 어디야", "일반지식"),
    ("파이썬 리스트 정렬하는 법", "일반지식"),
    ("상대성 이론 쉽게 설명해줘", "일반지식"),
    ("영어 공부 어떻게 시작해", "일반지식"),
    ("이차방정식 근의 공식 뭐였지", "일반지식"),
    # 인물 · 시사
    ("손흥민 이번 시즌 몇 골이야", "시사"),
    ("어제 야구 결과 알려줘", "시사"),
    ("요즘 인기 드라마 뭐 있어", "시사"),
    # 의료 · 법률 — 잘못 답하면 대가가 가장 큰 부류.
    ("감기 걸렸는데 무슨 약 먹어야 돼", "의료법률"),
    ("전세 계약 파기하면 위약금 얼마야", "의료법률"),
    ("허리 아픈데 무슨 병원 가야 해", "의료법률"),
    # 업무 · 도구 요청
    ("이메일 정중하게 써줘", "업무"),
    ("이 문장 영어로 번역해줘", "업무"),
    ("엑셀 vlookup 쓰는 법", "업무"),
    ("자기소개서 첨삭해줘", "업무"),
]


# --- 도메인 안인데 밖처럼 보이는 것 -----------------------------------------
#
# 게이트가 여기를 거절하면 **멀쩡한 검색이 막힌다.** 표면이 도메인 밖과 겹치도록
# 일부러 고른 것들이라, 명백한 질의만 넣었을 때보다 오거부가 나기 쉽다.
LOOKS_OUT_BUT_IN: list[tuple[str, str]] = [
    # 재화 — "돈" 이야기라 현실 금융과 어휘가 겹친다. 실제 취급 품목이다.
    ("골드 시세 어때?", "재화"),
    ("게임 머니 1000만 얼마에 팔려", "재화"),
    ("현금으로 골드 얼마나 살 수 있어", "재화"),
    ("골드 값 오를까", "재화"),
    # 계정 — "판다/산다" 가 중고거래처럼 읽힌다. 역시 취급 품목이다.
    ("만렙 계정 얼마에 팔려?", "계정"),
    ("계정 파는 거 시세 좀", "계정"),
    # 대상이 흐릿한 도메인 안 질의 — 게이트가 "구체적이지 않으면 밖" 으로
    # 동작하면 여기가 걸린다.
    ("싼 거 아무거나 추천해줘", "모호"),
    ("제일 비싼 게 뭐야", "모호"),
    ("돈 되는 거 뭐 있어", "모호"),
    ("요즘 값 많이 올랐어?", "모호"),
    ("괜찮은 매물 있나", "모호"),
    # 현실 화폐 단위가 섞인 도메인 안 질의.
    ("3만원 이하로 살 만한 거", "가격조건"),
    ("10만원짜리 아이템 뭐 있어", "가격조건"),
    # 은어 · 축약 — LLM 이 잘 만들지 않는 형태.
    ("현질템 시세 좀", "은어"),
    ("만렙템 어디서 구함", "은어"),
    ("풀강 무기 얼마임?", "은어"),
]


OUT_OF_DOMAIN_QUERIES = [query for query, _ in OUT_OF_DOMAIN]
LOOKS_OUT_BUT_IN_QUERIES = [query for query, _ in LOOKS_OUT_BUT_IN]


def _assert_disjoint() -> None:
    """두 목록이 겹치면 어느 쪽으로 채점해도 틀린다 — 조용히 넘어가면 안 된다."""
    overlap = set(OUT_OF_DOMAIN_QUERIES) & set(LOOKS_OUT_BUT_IN_QUERIES)
    if overlap:
        raise ValueError(f"두 목록에 같은 질의가 있습니다: {sorted(overlap)}")
    for name, queries in (
        ("OUT_OF_DOMAIN", OUT_OF_DOMAIN_QUERIES),
        ("LOOKS_OUT_BUT_IN", LOOKS_OUT_BUT_IN_QUERIES),
    ):
        if len(set(queries)) != len(queries):
            raise ValueError(f"{name} 안에 중복 질의가 있습니다")


_assert_disjoint()
