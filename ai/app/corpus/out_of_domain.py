# --- 라벨이 갈리는 것 — **채점하지 않는다** ---------------------------------
#
# 어느 쪽으로 라벨을 붙여도 논증이 되는 질의다. 채점 세트에 넣으면 프롬프트가
# 아니라 **내 라벨을 재게 된다.** 혼잣말 부류를 held-out 에서 뺀 것과 같은 이유고,
# 지우지 않고 남기는 이유는 **다음에 세트를 만들 사람이 같은 고민을 다시 하지
# 않게** 하기 위해서다.
AMBIGUOUS_LABEL: list[tuple[str, str]] = [
    # 배포본 실측(2026-08-07): `item_search` 로 가서 **강화 주문서 (성공률 70%)**
    # 를 포함한 5건을 돌려줬다. "방법" 을 물었으니 게임 플레이 질문이라는 읽기와,
    # 거래소의 정직한 답이 "그 확률을 올려주는 물건을 판다" 라는 읽기가 **둘 다
    # 성립한다.** `전사 스킬트리 추천해줘`(밖)와 달리 상업적 답이 실재한다.
    (
        "강화 확률 올리는 방법 있어?",
        "게임메커니즘/거래 경계 — 답이 실제로 취급 품목이라 밖이라 단정 못 한다",
    ),
]

AMBIGUOUS_QUERIES = [query for query, _ in AMBIGUOUS_LABEL]

OUT_OF_DOMAIN_QUERIES = [query for query, _ in OUT_OF_DOMAIN]
LOOKS_OUT_BUT_IN_QUERIES = [query for query, _ in LOOKS_OUT_BUT_IN]
HOLDOUT_QUERIES = [query for query, _ in HOLDOUT_IN + HOLDOUT_OUT]


def _assert_disjoint() -> None:
    """두 목록이 겹치면 어느 쪽으로 채점해도 틀린다 — 조용히 넘어가면 안 된다."""
    overlap = set(OUT_OF_DOMAIN_QUERIES) & set(LOOKS_OUT_BUT_IN_QUERIES)
    if overlap:
        raise ValueError(f"두 목록에 같은 질의가 있습니다: {sorted(overlap)}")
    for name, queries in (
        ("OUT_OF_DOMAIN", OUT_OF_DOMAIN_QUERIES),
        ("LOOKS_OUT_BUT_IN", LOOKS_OUT_BUT_IN_QUERIES),
        ("HOLDOUT", HOLDOUT_QUERIES),
    ):
        if len(set(queries)) != len(queries):
            raise ValueError(f"{name} 안에 중복 질의가 있습니다")

    # **held-out 이 tune 세트와 한 건이라도 겹치면 held-out 이 아니다.**
    # 겹친 채로도 숫자는 멀쩡히 나오므로, 이건 조용히 틀리는 종류다.
    tune = set(OUT_OF_DOMAIN_QUERIES) | set(LOOKS_OUT_BUT_IN_QUERIES)
    leaked = tune & set(HOLDOUT_QUERIES)
    if leaked:
        raise ValueError(f"held-out 이 tune 세트와 겹칩니다: {sorted(leaked)}")

    # **라벨이 갈린다고 빼놓고 어딘가에서 채점하면 뺀 의미가 없다.**
    scored = tune | set(HOLDOUT_QUERIES)
    still_scored = scored & set(AMBIGUOUS_QUERIES)
    if still_scored:
        raise ValueError(f"라벨 보류 질의가 채점 세트에 있습니다: {sorted(still_scored)}")


def _assert_v1_still_resolves() -> None:
    """v1 부분집합이 **문자열로** 정의돼 있어서, 본문을 고치면 조용히 어긋난다.

    어긋나면 v1 분모가 소리 없이 줄어들고, ADR-0039 와의 비교가 "같은 표본"이
    아니게 된다 — 그런데 출력은 여전히 그럴듯한 숫자다. 그 침묵을 막는다.
    """
    missing = BOUNDARY_V1 - set(LOOKS_OUT_BUT_IN_QUERIES)
    if missing:
        raise ValueError(f"BOUNDARY_V1 에만 있는 질의: {sorted(missing)}")
    if len(BOUNDARY_V1) != 16:
        raise ValueError(f"v1 경계는 16건이어야 합니다 (지금 {len(BOUNDARY_V1)})")

    stale = OOD_V1_EXCLUDED - set(OUT_OF_DOMAIN_QUERIES)
    if stale:
        raise ValueError(f"OOD_V1_EXCLUDED 에만 있는 질의: {sorted(stale)}")
