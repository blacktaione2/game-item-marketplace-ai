"""속성(element) 추출 평가셋 — 전부 수작업, 정답 라벨이 붙어 있다.

## 왜 이제야 생겼나

`"무속성 검 찾아줘"` 가 `element="무속성"` 을 50번 중 8번만 낸다. 나머지 42번은
`null` 이다 — 모델이 "무속성" 을 **"속성 언급 없음"** 으로 읽는다. 그래서 무속성
검을 요청해도 불꽃의 대검이 섞여 나온다.

로드맵은 이 항목의 선행 조건을 **"정답 붙은 평가셋"** 이라고 적어뒀다. 기존
하네스로는 잴 수 없었기 때문이다.

- `evaluate_rewrite_determinism.py` 는 **안정성**을 잰다 — 같은 질의를 두 번
  돌려 답이 같은지. 두 번 다 틀려도 만점이다.
- `evaluate_hard_filters.py` 는 필터가 **걸린 뒤** 부적합 결과 수를 센다. 필터가
  아예 안 걸리는 경우는 그 지표에 안 나타난다.

그리고 결정적인 이유가 하나 더 있다: **`data/` 의 질의 547건 중 `무속성` 을
언급하는 것이 0건이다.** 재는 도구가 없었던 게 아니라 **잴 입력이 없었다.**

## 네 무리로 나눈 이유

한 방향만 재면 반대쪽 극단이 만점을 받는다 — 도메인 게이트에서 이미 겪었다.
여기서 그 극단은 **"전부 무속성으로 채우기"** 다.

| 무리 | 정답 | 이게 없으면 |
|---|---|---|
| `무속성` | `"무속성"` | 고치려는 결함이 안 보인다 |
| `타속성` | 해당 속성 | 무속성 고치다 다른 속성을 덮어써도 모른다 |
| **`미언급`** | `None` | **"전부 무속성"이 만점을 받는다** |
| `저항` | `None` | `"화염 저항 방어구"` 가 화염 속성으로 걸린다 |

`미언급` 무리에 `"속성 좋은 무기"` 를 일부러 넣었다 — `속성` 이라는 낱말은
있는데 답은 `None` 이다. 낱말로 미는 구현은 여기서 걸린다. 이 저장소가 한국어
정규식에서 두 번, 프롬프트에서 두 번 겪은 실패의 예방접종이다.

## 부정형은 별도 집계다 — **알려진 한계이지 목표가 아니다**

`"무속성 아닌 검"` 의 옳은 답은 "무속성을 제외한 전부" 인데, `SearchFilters` 는
그걸 표현할 수 없다(`element` 는 동등 비교 하나뿐이다). 그래서 정답을 `None`
(필터 없음)으로 둔다 — **맞는 답이라서가 아니라 표현 가능한 최선이라서**다.

여기서 재는 것은 "부정형을 알아듣는가" 가 아니라 **"부정형에 무속성을 잘못
채우지 않는가"** 다. 채우면 사용자가 원한 것의 정반대를 준다.
"""

from __future__ import annotations

# (질의, 정답 element, 무리)
#
# 정답은 `SearchFilters.element` 에 들어갈 값이다. `None` 은 "속성으로 거르지
# 않는다" 이고 `"무속성"` 은 "속성이 없는 아이템만" 이다 — 이 둘의 혼동이 애초에
# 이 결함의 정체다.
ELEMENT_QUERIES: list[tuple[str, str | None, str]] = [
    # --- 무속성을 명시했다 -------------------------------------------------
    ("무속성 검 찾아줘", "무속성", "무속성"),
    ("무속성 활 있어?", "무속성", "무속성"),
    ("속성 없는 갑옷 보여줘", "무속성", "무속성"),
    ("속성없는 지팡이 추천", "무속성", "무속성"),
    ("무속성 무기 중에 싼 거", "무속성", "무속성"),
    ("무속성인 반지 있나", "무속성", "무속성"),
    ("무속성 방패 5만원 이하", "무속성", "무속성"),
    ("속성 없는 장비 목록", "무속성", "무속성"),
    ("무속성 목걸이 얼마야", "무속성", "무속성"),
    ("무속성 물약 뭐 있어", "무속성", "무속성"),
    ("무속성의 대검 찾습니다", "무속성", "무속성"),
    ("무속성 각반 추천해줘", "무속성", "무속성"),
    ("무속성 둔기 시세", "무속성", "무속성"),
    # **일부러 넣은 미수록 표현.** 아래 구현의 키워드 목록에 없다 — 한계를
    # 숫자로 드러내려고 둔다. 전부 맞는 평가셋은 한계를 못 보여준다.
    ("속성 안 붙은 신발", "무속성", "무속성"),
    # --- 다른 속성을 명시했다 (회귀 확인) ----------------------------------
    ("화염 속성 검 찾아줘", "화염", "타속성"),
    ("불속성 대검", "화염", "타속성"),
    ("얼음 속성 지팡이", "냉기", "타속성"),
    ("냉기 활 있어?", "냉기", "타속성"),
    ("번개 속성 창", "번개", "타속성"),
    ("어둠 속성 로브", "암흑", "타속성"),
    ("신성 속성 방패", "신성", "타속성"),
    ("빛 속성 목걸이", "신성", "타속성"),
    # --- 속성을 언급하지 않았다 (정답은 필터 없음) -------------------------
    #
    # **여기가 "전부 무속성" 을 막는 자리다.**
    ("검 찾아줘", None, "미언급"),
    ("3만원 이하 갑옷", None, "미언급"),
    ("+9 강화 롱소드 시세", None, "미언급"),
    ("100렙 이상 활", None, "미언급"),
    ("싼 아이템 추천", None, "미언급"),
    # `속성` 이라는 낱말은 있는데 답은 None 이다. 낱말로 미는 구현이 걸린다.
    ("속성 좋은 무기", None, "미언급"),
    ("공격력 높은 검", None, "미언급"),
    ("방어구 목록 보여줘", None, "미언급"),
    ("경매로 나온 반지", None, "미언급"),
    ("강화 수치 높은 지팡이", None, "미언급"),
    # --- 저항 (정답은 필터 없음) -------------------------------------------
    #
    # element 는 그 아이템이 **내는** 속성이고 저항은 별개 축이다.
    ("화염 저항 방어구", None, "저항"),
    ("냉기 저항 로브 있어?", None, "저항"),
    ("암흑 저항 목걸이", None, "저항"),
    ("속성 저항 높은 갑옷", None, "저항"),
    # --- 부정형 (알려진 한계, 별도 집계) -----------------------------------
    #
    # 정답 `None` 은 "맞는 답" 이 아니라 **표현 가능한 최선**이다.
    # 재는 것은 "무속성을 잘못 채우지 않는가" 다.
    ("무속성 아닌 검", None, "부정형"),
    ("무속성 말고 다른 거", None, "부정형"),
    ("무속성 빼고 보여줘", None, "부정형"),
]

ELEMENT_GROUPS = ("무속성", "타속성", "미언급", "저항", "부정형")


def _assert_well_formed() -> None:
    """라벨이 스키마 밖 값이면 채점이 조용히 어긋난다."""
    valid = {"화염", "냉기", "번개", "암흑", "신성", "무속성", None}
    for query, answer, group in ELEMENT_QUERIES:
        if answer not in valid:
            raise ValueError(f"모르는 정답 라벨: {answer!r} ({query})")
        if group not in ELEMENT_GROUPS:
            raise ValueError(f"모르는 무리: {group!r} ({query})")

    queries = [query for query, _, _ in ELEMENT_QUERIES]
    if len(set(queries)) != len(queries):
        raise ValueError("중복 질의가 있습니다")

    # **`미언급` 무리가 비면 "전부 무속성" 이 만점을 받는다.** 한 방향만 재는
    # 지표는 반대쪽 극단을 최적해로 만든다 — 도메인 게이트에서 이미 겪었다.
    counts = {group: 0 for group in ELEMENT_GROUPS}
    for _, _, group in ELEMENT_QUERIES:
        counts[group] += 1
    if counts["미언급"] < 5:
        raise ValueError(f"미언급 무리가 너무 적습니다: {counts['미언급']}")
    if counts["무속성"] < 5:
        raise ValueError(f"무속성 무리가 너무 적습니다: {counts['무속성']}")


_assert_well_formed()
